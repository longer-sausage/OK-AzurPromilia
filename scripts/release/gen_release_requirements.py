#!/usr/bin/env python3
"""从 uv.lock 导出 Windows x64 / Python 3.12 的完整运行依赖。

Qt 由框架的 qt extra 提供。PyAppify 使用 --no-deps 安装此锁定清单。

    生成并覆盖 requirements.txt：
      uv run --locked python scripts/release/gen_release_requirements.py

    校验已提交的 requirements.txt 与生成结果一致（CI 使用）：
      uv run --locked python scripts/release/gen_release_requirements.py --check
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

try:
    from packaging.markers import Marker
except ImportError:
    Marker = None  # type: ignore[assignment]

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "requirements.txt"

# 目标发布平台：Windows x64 + Python 3.12
WINDOWS_ENV = {
    "os_name": "nt",
    "sys_platform": "win32",
    "platform_machine": "AMD64",
    "platform_python_implementation": "CPython",
    "platform_release": "10",
    "platform_system": "Windows",
    "platform_version": "10.0.19045",
    "python_full_version": "3.12.10",
    "python_version": "3.12",
    "implementation_name": "cpython",
}

HEADER = """\
# This file was autogenerated from uv.lock via the following command:
#    uv run --locked python scripts/release/gen_release_requirements.py
# 重新生成：
#   uv run --locked python scripts/release/gen_release_requirements.py
# 校验（CI）：
#   uv run --locked python scripts/release/gen_release_requirements.py --check
"""


def generate_compiled() -> str:
    """从 uv.lock 导出 requirements 格式清单（与锁文件版本一致，不含 dev 组）。"""
    cmd = ["uv", "export", "--locked", "--format", "requirements-txt", "--no-hashes", "--no-dev"]
    proc = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, encoding="utf-8")
    if proc.returncode != 0:
        sys.stderr.write(proc.stderr)
        raise SystemExit(f"uv export 失败: rc={proc.returncode}")
    return proc.stdout


def marker_applies(marker: str | None) -> bool:
    """判断环境标记是否适用于 Windows x64 + Python 3.12（解析失败时终止，不静默放行）。"""
    if not marker:
        return True
    if Marker is None:
        raise SystemExit("packaging.markers 不可用，无法解析依赖标记")
    try:
        return bool(Marker(marker).evaluate(WINDOWS_ENV))
    except Exception as exc:
        raise SystemExit(f"依赖标记解析/求值失败: {marker!r} ({exc})") from exc


def shrink(compiled: str) -> str:
    """仅保留目标平台适用的锁定版本。"""
    lines = compiled.splitlines()
    result: list[str] = [HEADER]
    for line in lines:
        if not line or line.lstrip().startswith("#"):
            continue
        requirement, _, marker = line.partition(";")
        if marker_applies(marker.strip()):
            result.append(requirement.rstrip())
    return "\n".join(result) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", default=str(OUTPUT), help="输出文件路径")
    parser.add_argument("--check", action="store_true", help="校验已提交文件与生成结果一致")
    args = parser.parse_args()

    output = Path(args.output).resolve()
    if not output.is_relative_to(ROOT):
        sys.stderr.write(f"输出路径必须在仓库内: {output}\n")
        return 1

    generated = shrink(generate_compiled())

    if args.check:
        if not output.exists():
            sys.stderr.write(f"缺少文件: {output}\n")
            return 1
        current = output.read_bytes()
        if current != generated.encode("utf-8"):
            sys.stderr.write("requirements.txt 与生成结果不一致，请重新生成:\n")
            sys.stderr.write("  uv run --locked python scripts/release/gen_release_requirements.py\n")
            return 1
        print("OK: requirements.txt 与生成结果一致")
        return 0

    output.write_text(generated, encoding="utf-8", newline="\n")
    print(f"已生成 {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
